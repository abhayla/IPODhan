// Self-test for scripts/ci/check-design-traceability.mjs (OD-52, §8.5).
// Each case below builds a tiny fixture tree in a temp dir and runs the REAL
// check script against it via a child process — the test never re-implements
// the check's parsing logic. Slice s1: failure modes 1-3 only (mode 4, the
// hash-drift check, is a later slice).

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SCRIPT = join(__dirname, '..', 'check-design-traceability.mjs');
// Repo root, for the one case that runs against the real files.
const REPO_ROOT = join(__dirname, '..', '..', '..');

// This test file lives under scripts/ci/tests/, one of the check's own real
// scan roots — so a literal "// implements: R-xxx" string embedded verbatim
// in this source would be picked up by the check when it later scans the
// REAL repo (the last test case below runs the check against real files).
// Build the header out of parts so the raw source never contains the
// contiguous "// implements:" substring; the runtime STRING VALUE written to
// each fixture file is still exactly that text.
const IMPLEMENTS_TAG = ['/', '/', ' implements: '].join('');

function writeFile(root, relPath, content) {
  const full = join(root, relPath);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content);
}

function mkFixtureRoot() {
  return mkdtempSync(join(tmpdir(), 'design-traceability-'));
}

function rulesJson(rules) {
  return JSON.stringify({ rules }, null, 2);
}

function rule(id, opts = {}) {
  return {
    id,
    hash: opts.hash || 'deadbeef0000',
    section: opts.section || '1.1 Fixture section',
    kind: opts.kind || 'prose',
    text: opts.text || 'A fixture rule.',
    first_seen: '2026-09-10',
    retired: !!opts.retired,
  };
}

function cardBody(idsLine) {
  return (
    '# Item 99 — fixture card\n\n' +
    '## Rules implemented\n\n' +
    '<!-- generated by docs/design/apply-rule-ownership.mjs - edits inside this block are overwritten -->\n\n' +
    '1 rule(s) from `docs/design/rules.json`.\n\n' +
    '| Design section | Rule ids |\n' +
    '|---|---|\n' +
    '| §1.1 | ' +
    idsLine +
    ' |\n\n' +
    '## Known gaps\n\n' +
    'None.\n'
  );
}

function runCheck(root, extraArgs = []) {
  return spawnSync(
    'node',
    [
      SCRIPT,
      '--rules',
      join(root, 'docs/design/rules.json'),
      '--cards',
      join(root, 'docs/design/build-cards'),
      '--unclaimed',
      join(root, 'docs/design/rules-unclaimed.json'),
      '--tests',
      join(root, 'tests'),
      ...extraArgs,
    ],
    { encoding: 'utf8' }
  );
}

test('mode 1: a live rule claimed by no card and not unclaimed -> exit 1, names the id', () => {
  const root = mkFixtureRoot();
  try {
    writeFile(root, 'docs/design/rules.json', rulesJson([rule('R-001')]));
    writeFile(root, 'docs/design/build-cards/item-99-fixture.md', cardBody('R-999-not-real'));
    writeFile(root, 'docs/design/rules-unclaimed.json', JSON.stringify({ unclaimed: {} }));
    writeFile(root, 'tests/unit/foo.test.mjs', '// nothing here\n');

    const res = runCheck(root);
    assert.equal(res.status, 1, res.stdout + res.stderr);
    assert.match(res.stdout + res.stderr, /R-001/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('mode 2: a card claims an id no test declares -> exit 0 (reporting mode), names card + id', () => {
  const root = mkFixtureRoot();
  try {
    writeFile(root, 'docs/design/rules.json', rulesJson([rule('R-002')]));
    writeFile(root, 'docs/design/build-cards/item-99-fixture.md', cardBody('R-002'));
    writeFile(root, 'docs/design/rules-unclaimed.json', JSON.stringify({ unclaimed: {} }));
    writeFile(root, 'tests/unit/foo.test.mjs', '// nothing declared here\n');

    const res = runCheck(root);
    assert.equal(res.status, 0, res.stdout + res.stderr);
    assert.match(res.stdout, /R-002/);
    assert.match(res.stdout, /item-99-fixture\.md/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('mode 3: a test declares R-999 which is not live -> exit 1, names the test file + id', () => {
  const root = mkFixtureRoot();
  try {
    writeFile(root, 'docs/design/rules.json', rulesJson([rule('R-003')]));
    writeFile(root, 'docs/design/build-cards/item-99-fixture.md', cardBody('R-003'));
    writeFile(root, 'docs/design/rules-unclaimed.json', JSON.stringify({ unclaimed: {} }));
    writeFile(root, 'tests/unit/bar.test.mjs', IMPLEMENTS_TAG + 'R-003, R-999\n');

    const res = runCheck(root);
    assert.equal(res.status, 1, res.stdout + res.stderr);
    const out = res.stdout + res.stderr;
    assert.match(out, /R-999/);
    assert.match(out, /bar\.test\.mjs/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

