test('MAJOR 1 regression: zero surviving test roots -> exit 2, never a silent PASS', () => {
  const root = mkFixtureRoot();
  try {
    writeFile(root, 'docs/design/rules.json', rulesJson([rule('R-777')]));
    writeFile(root, 'docs/design/build-cards/item-99-fixture.md', cardBody('R-777'));
    writeFile(root, 'docs/design/rules-unclaimed.json', JSON.stringify({ unclaimed: {} }));
    // Deliberately do NOT create the tests root — this reproduces the
    // reviewer's finding: `--tests <nonexistent>` used to print
    // "1 rules, 1 claimed, 0 orphans ... PASS" and exit 0, silently
    // disarming mode 3 for the whole population of test declarations.
    const res = spawnSync(
      'node',
      [
        SCRIPT,
        '--rules',
        join(root, 'docs/design/rules.json'),
        '--cards',
        join(root, 'docs/design/build-cards'),
        '--unclaimed',
        join(root, 'docs/design/rules-unclaimed.json'),
        '--tests',
        join(root, 'tests-does-not-exist'),
      ],
      { encoding: 'utf8' }
    );
    assert.equal(res.status, 2, res.stdout + res.stderr);
    assert.match(res.stdout + res.stderr, /zero test roots/i);
    assert.match(res.stdout + res.stderr, /tests-does-not-exist/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('MAJOR 2 regression: heading anchor recognises the real heading even when prose mentions it first', () => {
  const root = mkFixtureRoot();
  try {
    writeFile(root, 'docs/design/rules.json', rulesJson([rule('R-050')]));
    // Mirrors the real item-19 card bug: prose ABOVE the real heading
    // mentions the heading text in backticks, mid-document, before the
    // actual "## Rules implemented" heading. A plain indexOf() finds the
    // prose mention instead of the real heading and loses the claim below
    // it — this must stay green with the anchored regex and would go RED
    // if the anchor were reverted to indexOf().
    const card =
      '# Item 99 — fixture card\n\n' +
      '## Some other section\n\n' +
      'Its `## Rules implemented` block is generated from the rule-ownership mapping ' +
      'and should not be confused with the real heading below.\n\n' +
      '## Rules implemented\n\n' +
      '<!-- generated by docs/design/apply-rule-ownership.mjs - edits inside this block are overwritten -->\n\n' +
      '1 rule(s) from `docs/design/rules.json`.\n\n' +
      '| Design section | Rule ids |\n' +
      '|---|---|\n' +
      '| §1.1 | R-050 |\n\n' +
      '## Known gaps\n\n' +
      'None.\n';
    writeFile(root, 'docs/design/build-cards/item-99-fixture.md', card);
    writeFile(root, 'docs/design/rules-unclaimed.json', JSON.stringify({ unclaimed: {} }));
    writeFile(root, 'tests/unit/foo.test.mjs', IMPLEMENTS_TAG + 'R-050\n');

    const res = runCheck(root);
    // R-050 must be recognised as claimed — if the anchor is reverted to
    // indexOf(), the prose mention wins, the real heading's claim is lost,
    // and R-050 shows up as a MODE 1 orphan (exit 1) instead.
    assert.equal(res.status, 0, res.stdout + res.stderr);
    assert.doesNotMatch(res.stdout, /MODE 1/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('MODE2_ENFORCE=true path: a card claim with no declaring test now exits 1', () => {
  const root = mkFixtureRoot();
  try {
    writeFile(root, 'docs/design/rules.json', rulesJson([rule('R-008')]));
    writeFile(root, 'docs/design/build-cards/item-99-fixture.md', cardBody('R-008'));
    writeFile(root, 'docs/design/rules-unclaimed.json', JSON.stringify({ unclaimed: {} }));
    writeFile(root, 'tests/unit/foo.test.mjs', '// nothing declared here\n');

    const res = spawnSync(
      'node',
      [
        SCRIPT,
        '--rules',
        join(root, 'docs/design/rules.json'),
        '--cards',
        join(root, 'docs/design/build-cards'),
        '--unclaimed',
        join(root, 'docs/design/rules-unclaimed.json'),
        '--tests',
        join(root, 'tests'),
      ],
      { encoding: 'utf8', env: { ...process.env, DESIGN_TRACEABILITY_MODE2_ENFORCE: 'true' } }
    );
    assert.equal(res.status, 1, res.stdout + res.stderr);
    assert.match(res.stdout, /MODE 2 \(ENFORCING\)/);
    assert.match(res.stdout, /R-008/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('real repo: the check parses the actual rules.json/cards/tests and never exits 2', () => {
  const res = spawnSync('node', [SCRIPT], { cwd: REPO_ROOT, encoding: 'utf8' });
  // A real finding (exit 1) is allowed and must be reported, never silenced.
  // Exit 2 would mean the check itself cannot even parse the repo's own
  // real files, which is a defect in the check.
  assert.notEqual(res.status, 2, res.stdout + res.stderr);
  assert.match(res.stdout, /\d+ rules?, \d+ claimed, \d+ orphan/i);
});
