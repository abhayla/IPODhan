#!/usr/bin/env node
// docs/design/apply-rule-ownership.mjs
//
// WHY. OD-52 asks that every build card list the design rules it implements. Twenty-two cards and
// 147 rules is 147 decisions, and typing them by hand into cards is how a rule ends up on two cards
// or none. So the mapping is authored ONCE, by section, in rule-ownership.json, and this writes the
// per-card blocks from it.
//
// What this is NOT: it is not the check. D19 reads the CARDS. If a card is corrected by hand,
// D19 believes the card — which is the right way round, because a human editing a card is making a
// deliberate statement and a regenerated block is only a convenience.
//
//   node docs/design/apply-rule-ownership.mjs           report what would change
//   node docs/design/apply-rule-ownership.mjs --apply   write the blocks into the cards
//   node docs/design/apply-rule-ownership.mjs --unclaimed  also write rules-unclaimed.json
//
// EXIT: 0 fine · 1 a section in rules.json has no row in rule-ownership.json, or a card was
//         REFUSED · 2 broke.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const CARDS = path.join(HERE, 'build-cards');

// The line that says "this block is machine-owned". Everything between the `## Rules implemented`
// heading and `## Known gaps` is CANDIDATE territory, so it must be UNAMBIGUOUS that a person's
// prose does not belong there. A reviewer proved on 2026-09-09 that without this the tool deletes
// hand-written content silently and reports success.
export const MARKER = '<!-- generated by docs/design/apply-rule-ownership.mjs - edits inside this block are overwritten -->';

// Issue #905: the marker above says a block is machine-owned, but it never said WHERE the
// machine-owned text ENDS. The tool's only other boundary was the next heading ("## Known gaps"),
// so a human who added a section AFTER the generated table but BEFORE that heading — exactly what
// happened to item-21 ("## Status of this card's corrections...", 56 lines) — had that text
// silently deleted the next time anyone ran `--apply`, because the tool treated the whole
// heading-to-heading span as its own. This end marker gives the generated block an explicit,
// literal boundary: only the text from `## Rules implemented` through this line is ever rewritten;
// everything after it (up to `## Known gaps`) is the card author's, byte-for-byte, forever.
export const END_MARKER = '<!-- end generated -->';

// #1106: 20 cards' "## Rules implemented" blocks cite `.claude/rules/*.md` governance-rule files
// (which project rules the build followed), not `docs/design/rules.json` R-nnn design-rule ids —
// a different vocabulary the generator cannot produce, and for most of these cards
// `rule-ownership.json` maps zero or one R-nnn id for the owning item, so regenerating would
// silently drop every governance-rule citation the card names. A card author who intends this
// list to stay hand-owned marks it with this line right after the `## Rules implemented` heading;
// the tool then reports it as SKIPPED (exit 0), never REFUSED and never rewritten.
export const HAND_OWNED_MARKER = '<!-- hand-owned: not generated by apply-rule-ownership.mjs, see docs/design/apply-rule-ownership.mjs HAND_OWNED_MARKER -->';

// Builds the generated block text (no trailing card-specific whitespace) for one card's rule list.
export function buildBlock(mine) {
  const bySec = new Map();
  for (const r of mine) {
    const s = r.section.split(' ')[0];
    if (!bySec.has(s)) bySec.set(s, []);
    bySec.get(s).push(r.id);
  }
  const lines = [];
  lines.push('## Rules implemented');
  lines.push('');
  lines.push(MARKER);
  lines.push('');
  if (!mine.length) {
    lines.push('None. This item implements no numbered rule of the design — it is scaffolding for');
    lines.push('the items that do. Stated explicitly rather than left blank, because an empty list and');
    lines.push('a forgotten list look identical.');
  } else {
    lines.push(`${mine.length} rule(s) from \`docs/design/rules.json\`, generated by`);
    lines.push('`node docs/design/apply-rule-ownership.mjs --apply` from `rule-ownership.json`.');
    lines.push('');
    lines.push('| Design section | Rule ids |');
    lines.push('|---|---|');
    for (const [s, ids] of [...bySec.entries()].sort()) {
      lines.push(`| §${s.replace(/\.$/, '')} | ${ids.join(', ')} |`);
    }
  }
  lines.push('');
  lines.push(END_MARKER);
  return lines.join('\n');
}

/**
 * Splices a freshly generated block into one card's markdown text.
 *
 * Returns `{ next, changed, refused }` where:
 *   - `refused` is a string reason (the run must exit 1, card left untouched, `next` is `md`), or
 *     `null` when the splice is safe.
 *   - `next` is the new file content (only meaningful when `refused` is null).
 *   - `changed` is true when `next !== md`.
 *
 * Pure and file-I/O-free so `scripts/tests/apply-rule-ownership.test.mjs` can drive every branch
 * (fresh card, marker-and-end-marker card, pre-migration marker-only card, hand-written card, a
 * heading merely discussed in prose) without touching `docs/design/build-cards/`.
 */
export function spliceGeneratedBlock(md, block, fileLabel) {
  const eol = md.includes('\r\n') ? '\r\n' : '\n';
  const blockEol = block.split('\n').join(eol);
  // Anchored at the START OF A LINE, and taking the LAST occurrence. The first version matched
  // anywhere and took the first hit: item 20's card DISCUSSES the "## Rules implemented" block in
  // its Interfaces section, so the tool spliced from inside that sentence and deleted seven
  // headings and half the card. A rewriting tool that can silently delete the document it is
  // editing is worse than no tool, so this now also refuses any rewrite that loses a heading.
  const RULES_H = eol + '## Rules implemented';
  const GAPS_H = eol + '## Known gaps';
  const hasRules = md.lastIndexOf(RULES_H) >= 0;
  const hasGaps = md.lastIndexOf(GAPS_H) >= 0;

  if (hasRules) {
    const start = md.lastIndexOf(RULES_H) + eol.length;
    const end = hasGaps ? md.lastIndexOf(GAPS_H) + eol.length : md.length;
    if (hasGaps && end < start) {
      return { next: md, changed: false, refused: `"## Known gaps" sits before "## Rules implemented"; fix the card by hand.` };
    }
    const existingSpanEnd = hasGaps ? md.lastIndexOf(GAPS_H) : md.length;
    const existing = md.slice(start, existingSpanEnd);

    // #1106: a card author can declare a hand-written list permanently hand-owned. This is
    // checked before the marker/refusal logic below so a hand-owned card is never touched and
    // never refused — it is reported SKIPPED and the run still exits 0 for it.
    if (existing.includes(HAND_OWNED_MARKER)) {
      return { next: md, changed: false, refused: null, skipped: true };
    }

    // The block this tool owns must SAY it is owned. If a card already has a rules block and that
    // block does not carry the marker, somebody wrote it by hand and this tool does not get to
    // delete it.
    //
    // Two things count as "this tool wrote it": the marker (everything written from now on), or
    // the placeholder a card author is told to leave (`Generated by apply-rule-ownership.mjs.`) —
    // used once to migrate the 22 cards that predated the marker; that migration is done.
    const placeholder = /Generated by apply-rule-ownership\.mjs\.?\s*$/m.test(existing.trim());
    if (!existing.includes(MARKER) && !placeholder) {
      return { next: md, changed: false, refused: 'the existing rules block carries no generator marker, so it was written by hand. Card left untouched; delete the block yourself if you want it regenerated.' };
    }

    // Issue #905: the marker alone does not say where the generated text ENDS, so anything a human
    // added after the generated table (and before "## Known gaps") reads as part of "the block this
    // tool owns" and gets silently deleted on the next --apply. A card written before this end
    // marker existed cannot be told apart from one that still has zero hand-written additions, so
    // this refuses rather than guesses — it never deletes on the strength of an assumption.
    const endMarkerIdx = existing.indexOf(END_MARKER);
    if (endMarkerIdx === -1) {
      return {
        next: md,
        changed: false,
        refused: `the generated block has no "${END_MARKER}" end marker yet (pre-migration card) — this tool cannot tell hand-written text after the generated table apart from its own old output, so it refuses rather than risk deleting it. Add the marker by hand right after the generated lines, then re-run.`,
      };
    }
    // Everything after the end marker, up to "## Known gaps" (or end of file), is the card
    // author's and is carried forward byte-for-byte, whatever it says.
    const afterGenerated = existing.slice(endMarkerIdx + END_MARKER.length);
    const gapsTail = hasGaps ? md.slice(md.lastIndexOf(GAPS_H)) : '';
    const next = md.slice(0, start) + blockEol + afterGenerated + gapsTail;
    return { next, changed: next !== md, refused: null };
  }

  // No existing block: append a fresh one plus a "## Known gaps" scaffold.
  const next = md.trimEnd() + eol + eol + blockEol + eol + eol +
    '## Known gaps' + eol + eol +
    'None recorded yet. A finding this item owns but does not close is written here, with its' + eol +
    'id and the reason — that is what stops "zero open findings" being reached by dropping one.' + eol;
  return { next, changed: next !== md, refused: null };
}

async function main() {
  const apply = process.argv.includes('--apply');
  const rules = JSON.parse(fs.readFileSync(path.join(HERE, 'rules.json'), 'utf8'))
    .rules.filter((r) => !r.retired);
  const own = JSON.parse(fs.readFileSync(path.join(HERE, 'rule-ownership.json'), 'utf8'));

  const byItem = new Map();
  const unclaimed = {};
  const unmapped = new Set();

  for (const r of rules) {
    const sec = r.section.split(' ')[0];
    if (!(sec in own.sections)) { unmapped.add(sec); continue; }
    const items = own.sections[sec];
    if (items === null) {
      unclaimed[r.id] = `${sec} — ${own._unclaimed_sections[sec] || 'declared unclaimed'}`;
      continue;
    }
    for (const it of items) {
      if (!byItem.has(it)) byItem.set(it, []);
      byItem.get(it).push(r);
    }
  }

  if (unmapped.size) {
    console.log(`FAIL — ${unmapped.size} section(s) in rules.json have no row in rule-ownership.json: ${[...unmapped].join(', ')}`);
    console.log('Every section must be mapped to a build item or explicitly to null with a reason.');
    process.exit(1);
  }

  const files = fs.readdirSync(CARDS).filter((f) => /^item-\d+-.*\.md$/.test(f)).sort();
  let changed = 0;
  let skipped = 0;
  for (const f of files) {
    const n = Number(f.match(/^item-(\d+)/)[1]);
    const mine = (byItem.get(n) || []).sort((a, b) => a.id.localeCompare(b.id));
    const block = buildBlock(mine);
    const md = fs.readFileSync(path.join(CARDS, f), 'utf8');

    const result = spliceGeneratedBlock(md, block, f);
    if (result.refused) {
      console.log(`${f}: REFUSED — ${result.refused}`);
      process.exitCode = 1;
      continue;
    }
    if (result.skipped) {
      skipped++;
      console.log(`${f}: SKIPPED — hand-owned (${HAND_OWNED_MARKER.slice(0, 40)}...)`);
      continue;
    }
    if (result.changed) {
      changed++;
      if (apply) fs.writeFileSync(path.join(CARDS, f), result.next);
    }
    console.log(`${f}: ${mine.length} rule(s)${result.changed ? (apply ? ' — written' : ' — WOULD CHANGE') : ''}`);
  }

  const UN = path.join(HERE, 'rules-unclaimed.json');
  const unOut = {
    _why: 'OD-52. A rule that no build item implements is allowed — the deploy cadence, the honest uncertainties, the language-model constraint are rules about how we WORK, not code. What is not allowed is silence. D19 fails on any rule id that is neither claimed by a card nor listed here with a reason.',
    _generated_by: 'docs/design/apply-rule-ownership.mjs',
    unclaimed,
  };
  if (apply) fs.writeFileSync(UN, JSON.stringify(unOut, null, 2) + '\n');
  console.log(`\n${changed} card(s) ${apply ? 'written' : 'would change'}; ${skipped} card(s) hand-owned (skipped); ${Object.keys(unclaimed).length} rule(s) declared unclaimed.`);
  // NOT `process.exit(0)`. That overrode every `process.exitCode = 1` a REFUSED card set above,
  // so the refusal printed and the run still reported success - a gate that cannot fail.
  process.exit(process.exitCode || 0);
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  main().catch((err) => {
    console.error('apply-rule-ownership: the tool itself failed —', err.message);
    process.exit(2);
  });
}
